
require('dotenv').config();

const express = require('express');
const nodemailer = require('nodemailer');
const path = require('path');

const app = express();
const PORT = Number(process.env.PORT || 3000);

app.use(express.json({ limit: '20kb' }));
app.use(express.static(__dirname));


function getTransporter() {
    const {
        SMTP_HOST,
        SMTP_PORT,
        SMTP_SECURE,
        SMTP_USER,
        SMTP_PASS
    } = process.env;

    if (!SMTP_HOST || !SMTP_PORT || !SMTP_USER || !SMTP_PASS) {
        throw new Error(
            'Email is not configured. Check your .env file.'
        );
    }

    return nodemailer.createTransport({
        host: SMTP_HOST,
        port: Number(SMTP_PORT),
        secure: String(SMTP_SECURE).toLowerCase() === 'true',
        auth: {
            user: SMTP_USER,
            pass: SMTP_PASS
        },
        tls: {
            rejectUnauthorized: true
        }
    });
}


app.post('/api/send-report', async (req, res) => {
    const {
        to,
        note,
        income,
        expenses,
        net,
        savingsGoal,
        topExpense
    } = req.body || {};

    // Validate recipient email
    if (
        typeof to !== 'string' ||
        to.length > 254 ||
        !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(to)
    ) {
        return res.status(400).json({
            error: 'Enter a valid recipient email address.'
        });
    }

    // Clean user-provided text
    const clean = (value, max = 200) =>
        typeof value === 'string'
            ? value.slice(0, max).replace(/[\r\n]/g, ' ')
            : 'Not available';

    const subject = 'Your FlexiCredit Monthly Finance Summary';

    const text = [
        'Hello,',
        '',
        'Here is your FlexiCredit finance summary:',
        '',
        `Total income: ${clean(income, 40)}`,
        `Total expenses: ${clean(expenses, 40)}`,
        `Net cash flow: ${clean(net, 40)}`,
        `Savings goal: ${clean(savingsGoal)}`,
        `Top expense category: ${clean(topExpense)}`,
        ...(note ? ['', `Note: ${clean(note, 160)}`] : []),
        '',
        'Generated by FlexiCredit.'
    ].join('\n');

    try {
        const transporter = getTransporter();

      

        await transporter.sendMail({
            from: process.env.MAIL_FROM || process.env.SMTP_USER,
            to,
            subject,
            text
        });

        console.log(`Finance report sent to ${to}`);

        return res.json({
            ok: true,
            message: 'Finance report sent successfully.'
        });

    } catch (error) {
        console.error('Email send failed:', error);

        return res.status(500).json({
            error: 'Email could not be sent. Check the server terminal and SMTP settings.'
        });
    }
});

app.listen(PORT, () => {
    console.log(`FlexiCredit is running at http://localhost:${PORT}`);
});
